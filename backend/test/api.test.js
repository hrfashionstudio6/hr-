import test,{after,before} from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import {MongoMemoryServer} from 'mongodb-memory-server';
import request from 'supertest';
import {createApp} from '../src/app.js';
import {Workspace,Employee,Attendance,Session} from '../src/models.js';
import {arrivalStatus,localDay,validSchedule} from '../src/time.js';
let mongo,app;
const origin='http://localhost:3000';
const post=(agent,path,payload)=>agent.post(path).set('Origin',origin).send(payload);
before(async()=>{process.env.APP_ORIGIN=origin;process.env.SETUP_KEY='test-setup-key-with-more-than-32-characters';mongo=await MongoMemoryServer.create();await mongoose.connect(mongo.getUri());await Promise.all([Workspace.init(),Employee.init(),Attendance.init(),Session.init()]);app=createApp();});
after(async()=>{await mongoose.disconnect();await mongo?.stop();});
test('HR and employee lifecycle with real MongoDB',async()=>{
const hr=request.agent(app),employee=request.agent(app),other=request.agent(app);
assert.equal((await hr.get('/api/workspace')).status,401);
assert.equal((await post(hr,'/api/auth/setup',{company:'Test',name:'HR',email:'hr@example.com',password:'StrongPassword123!',timezone:'Asia/Karachi',setupKey:process.env.SETUP_KEY})).status,201);
const profile={action:'employee',name:'Ayesha',email:'ayesha@example.com',password:'EmployeePass123!',department:'Design',title:'Designer',joined:'2026-01-01',start:'09:00',end:'18:00'};
assert.equal((await post(hr,'/api/workspace',profile)).status,200);
assert.equal((await post(hr,'/api/workspace',profile)).status,409);
assert.equal((await post(hr,'/api/workspace',{...profile,name:'Hassan',email:'hassan@example.com'})).status,200);
assert.equal((await post(employee,'/api/auth/login',{email:profile.email,password:profile.password})).status,200);
assert.equal((await post(other,'/api/auth/login',{email:'hassan@example.com',password:profile.password})).status,200);
assert.equal((await employee.get('/api/workspace')).body.employees.length,1);
assert.equal((await post(employee,'/api/workspace',{action:'settings',company:'Unauthorized',timezone:'UTC'})).status,403);
assert.equal((await post(employee,'/api/workspace',{action:'checkout'})).status,409);
const concurrent=await Promise.all([post(employee,'/api/workspace',{action:'checkin'}),post(employee,'/api/workspace',{action:'checkin'})]);
assert.deepEqual(concurrent.map(r=>r.status).sort(),[200,409]);
assert.equal((await other.get('/api/workspace')).body.records.length,0);
assert.equal((await post(employee,'/api/workspace',{action:'checkout'})).status,200);
assert.equal((await post(employee,'/api/workspace',{action:'checkout'})).status,409);
assert.ok((await employee.get('/api/workspace')).body.records[0].checkOut);
assert.equal((await employee.post('/api/workspace').set('Origin','https://evil.example').send({action:'checkin'})).status,403);
assert.equal((await post(employee,'/api/auth/password',{currentPassword:profile.password,newPassword:'NewEmployeePass123!'})).status,200);
const id=(await hr.get('/api/workspace')).body.employees.find(e=>e.email===profile.email).id;
assert.equal((await post(hr,'/api/workspace',{action:'toggle',id,active:0})).status,200);
assert.equal((await employee.get('/api/workspace')).status,401);
assert.equal((await post(employee,'/api/auth/login',{email:profile.email,password:'NewEmployeePass123!'})).status,401);
assert.equal((await hr.get('/api/workspace')).body.records.length,1);
});
test('timezone and schedule boundaries',()=>{assert.equal(localDay(new Date('2026-01-01T23:00:00Z'),'Asia/Karachi'),'2026-01-02');assert.equal(arrivalStatus(new Date('2026-01-01T04:00:00Z'),'Asia/Karachi','09:00'),'Present');assert.equal(arrivalStatus(new Date('2026-01-01T04:01:00Z'),'Asia/Karachi','09:00'),'Late');assert.equal(validSchedule('22:00','06:00'),false);});
